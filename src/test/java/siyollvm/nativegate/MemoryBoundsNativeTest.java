package siyollvm.nativegate;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.TestFactory;
import siyollvm.Compiler;
import siyollvm.TestPaths;
import siyollvm.ir.IrStructure;
import siyollvm.toolchain.Clang;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertAll;
import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Memory-bound regression suite (R1). Every directory in
 * {@code src/test/resources/memory/} is a workload whose live data stays small
 * however long it runs, while it allocates (and drops) memory proportional to
 * its first argument N. Each is built once and run at the three sizes in its
 * {@code sizes} file, N1 &lt; N2 &lt; N3, under {@code SIYO_RT_STATS=1} and
 * {@code LC_ALL=C}, each in a fresh directory. For every N its stdout must
 * equal {@code expected-<N>.stdout}, generated by the JVM reference
 * ({@code scripts/memory-oracle.sh}), it must exit 0, and its stderr must be
 * exactly the stats line, from which {@code rss_peak_kb} is read. Then:
 *
 * <ul>
 *   <li>absolute bound: {@code rss(N3) <= bound} (64 MiB for every workload,
 *       see {@link #BOUND_KB});</li>
 *   <li>growth bound: {@code rss(N3) <= 1.5 * rss(N2) + 8 MiB}: N3 is twice
 *       N2, so memory that grows linearly with N (nothing reclaimed) fails it,
 *       while a bounded live set plus collector slack passes;</li>
 *   <li>flatness bound: {@code rss(N3) <= rss(N2) + 8 MiB}. With a bounded
 *       live set, peak RSS past the first collection threshold does not depend
 *       on N, so it must not creep as N doubles. This catches partial leaks (a
 *       leaked exception payload, a self-cycle that is never reclaimed) that
 *       grow slowly enough to stay under the 1.5x ratio bound and the absolute
 *       bound at these sizes.</li>
 * </ul>
 *
 * <p>The sizes were chosen so that the never-free runtime (before the R1
 * collector) peaks at roughly 140 to 255 MB RSS at N3, far above the bound and
 * still under the ~400 MB a native test may use; the measured numbers are in
 * {@code docs/evidence/r1-gc/red/}. A missing stats line is a failure.
 */
@Tag("native")
class MemoryBoundsNativeTest {
    private static final long MIB_KB = 1024;

    /**
     * Absolute bound on rss_peak_kb at N3, per workload. 64 MiB for all: each
     * workload's data live at any moment is at most a few MiB (the largest is
     * gc_arrays' kept array, 200 000 items of 8 bytes, at most 2 MiB with its
     * doubling slack; gc_lines holds one 500-line file, about 8 KiB, and its
     * lines), plus a process baseline of about 3 MiB. 64 MiB leaves more than
     * ten times that for conservative-scan false retention and for the heap
     * the collector lets grow between collections, while the never-free
     * runtime uses 140 MB or more at every N3.
     */
    private static final Map<String, Long> BOUND_KB = new LinkedHashMap<>();

    static {
        for (String name : List.of("gc_strings", "gc_arrays", "gc_maps", "gc_structs", "gc_cycles",
                "gc_exceptions", "gc_modules", "gc_lines")) {
            BOUND_KB.put(name, 64 * MIB_KB);
        }
    }

    private static final double GROWTH_FACTOR = 1.5;
    private static final long GROWTH_SLACK_KB = 8 * MIB_KB;
    private static final long FLAT_SLACK_KB = 8 * MIB_KB;

    private static Clang clang;

    @BeforeAll
    static void requireClang() throws Exception {
        clang = NativeRunner.clang();
    }

    @TestFactory
    Stream<DynamicTest> workloads() throws Exception {
        Path directory = TestPaths.projectDir().resolve("src/test/resources/memory");
        List<String> found;
        try (Stream<Path> dirs = Files.list(directory)) {
            found = dirs.filter(Files::isDirectory).map(p -> p.getFileName().toString()).sorted().toList();
        }
        assertEquals(BOUND_KB.keySet().stream().sorted().toList(), found,
                "every workload in " + directory + " needs a bound here, and every bound a workload");
        return found.stream().map(name -> DynamicTest.dynamicTest(name,
                () -> check(name, directory.resolve(name))));
    }

    private record Measure(long n, long heapKb, long rssKb) {}

    private static void check(String name, Path dir) throws Exception {
        long[] sizes = Arrays.stream(Files.readString(dir.resolve("sizes")).strip().split("\\s+"))
                .mapToLong(Long::parseLong).toArray();
        assertEquals(3, sizes.length, name + ": sizes must list N1 N2 N3");
        assertTrue(sizes[0] < sizes[1] && sizes[1] < sizes[2], name + ": sizes must increase");

        Path exe = build(name, dir.resolve("main.siyo"));
        List<Measure> measures = new ArrayList<>();
        for (long n : sizes) {
            measures.add(runAt(name, dir, exe, n));
        }
        long rss2 = measures.get(1).rssKb();
        long rss3 = measures.get(2).rssKb();
        long bound = BOUND_KB.get(name);
        long growthBound = (long) (GROWTH_FACTOR * rss2) + GROWTH_SLACK_KB;
        long flatBound = rss2 + FLAT_SLACK_KB;
        String table = name + " " + measures;
        assertAll(name + " memory bounds",
                () -> assertTrue(rss3 <= bound,
                        name + ": rss_peak_kb(N3=" + sizes[2] + ") = " + rss3 + " > bound " + bound + "; " + table),
                () -> assertTrue(rss3 <= growthBound,
                        name + ": rss_peak_kb(N3=" + sizes[2] + ") = " + rss3 + " > 1.5 * rss_peak_kb(N2="
                                + sizes[1] + ") + 8 MiB = " + growthBound + "; " + table),
                () -> assertTrue(rss3 <= flatBound,
                        name + ": rss_peak_kb(N3=" + sizes[2] + ") = " + rss3 + " > rss_peak_kb(N2="
                                + sizes[1] + ") + 8 MiB = " + flatBound + "; " + table));
    }

    private static Path build(String name, Path source) throws Exception {
        Compiler.IrResult ir = Compiler.toIr(source.getFileName().toString(), source.toAbsolutePath(),
                Files.readString(source));
        assertTrue(ir.diagnostics().isEmpty(), name + ": " + ir.diagnostics());
        IrStructure.assertWellFormed(ir.ir());
        Path work = Files.createDirectories(TestPaths.tempRoot().resolve("memory").resolve(name));
        Path ll = work.resolve(name + ".ll");
        Files.writeString(ll, ir.ir(), StandardCharsets.UTF_8);
        Path exe = work.resolve(name);
        clang.compile(ll, exe);
        return exe;
    }

    private static Measure runAt(String name, Path dir, Path exe, long n) throws Exception {
        Path work = exe.getParent();
        Path runDir = work.resolve("run-" + n);
        NativeRunner.Run removed = NativeRunner.run(List.of("rm", "-rf", "--", runDir.toString()), work, Map.of());
        assertEquals(0, removed.exitCode(), removed.stderr());
        Files.createDirectories(runDir);

        NativeRunner.Run run = NativeRunner.run(List.of(exe.toString(), Long.toString(n)), runDir, work,
                Map.of("LC_ALL", "C", "SIYO_RT_STATS", "1"));
        String label = name + " N=" + n;
        byte[] expected = Files.readAllBytes(dir.resolve("expected-" + n + ".stdout"));
        assertArrayEquals(expected, run.stdout(),
                label + " stdout:\n" + new String(run.stdout(), StandardCharsets.UTF_8));
        assertEquals(0, run.exitCode(), label + " exit code; stderr: " + run.stderr());

        String stderr = run.stderr();
        assertTrue(stderr.endsWith("\n"), label + ": no stats line on stderr: [" + stderr + "]");
        Matcher stats = RuntimeStatsNativeTest.STATS.matcher(stderr.substring(0, stderr.length() - 1));
        assertTrue(stats.matches(), label + ": stderr is not exactly the stats line: [" + stderr + "]");
        Measure measure = new Measure(n, Long.parseLong(stats.group(2)), Long.parseLong(stats.group(3)));
        // One line per run in the test output, for the evidence table.
        System.out.println("MEMORY " + name + " N=" + n + " collections=" + stats.group(1)
                + " heap_peak_kb=" + measure.heapKb() + " rss_peak_kb=" + measure.rssKb());
        return measure;
    }
}
